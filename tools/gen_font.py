#!/usr/bin/env python3
"""Generates src/app/font_data.h (anti-aliased bitmap font for the menus) from DejaVu Sans Mono Bold."""
import sys
from PIL import Image, ImageDraw, ImageFont
ttf = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/app/font_data.h'
CW, CH, SIZE = 10, 20, 16
chars = [chr(c) for c in range(32, 127)] + list('áéíóúÁÉÍÓÚñÑüÜ¿¡ºª·…←→↑↓‹›◄►©')
font = ImageFont.truetype(ttf, SIZE)
asc, desc = font.getmetrics()
lines = ['// Generated by tools/gen_font.py from DejaVu Sans Mono Bold (free license, see dejavu-fonts.github.io)',
         '#pragma once', '#include <stdint.h>', f'#define FONT_CW {CW}', f'#define FONT_CH {CH}',
         f'#define FONT_COUNT {len(chars)}',
         'static const uint32_t font_codepoints[FONT_COUNT] = {' + ','.join(str(ord(c)) for c in chars) + '};',
         'static const uint8_t font_alpha[FONT_COUNT][FONT_CH * FONT_CW] = {']
for c in chars:
    im = Image.new('L', (CW, CH), 0)
    d = ImageDraw.Draw(im)
    d.text((0, (CH - (asc + desc)) // 2 + 1), c, fill=255, font=font)
    lines.append('{' + ','.join(str(v) for v in im.tobytes()) + '},')
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
print(len(chars), 'glyphs')
